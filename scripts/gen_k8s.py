def edges() -> dict[str, list[str]]:
    """caller -> sorted callees, including the trace edge to agentops for every other service."""
    out: dict[str, list[str]] = {}
    for caller in SERVICES:
        callees = set(CALLS.get(caller, []))
        if caller != "agentops":
            callees.add("agentops")
        out[caller] = sorted(callees)
    for job, spec in JOBS.items():
        out[job] = sorted(spec["calls"])
    for cron in CRONJOBS:
        out[cron] = sorted(CRONJOBS[cron].get("calls", CRONJOB_CALLS))
    return out


def _callers(target: str) -> list[str]:
    return sorted(c for c, callees in edges().items() if target in callees)


def _port(name: str) -> list[int]:
    if name in DATA:
        return [DATA[name]["port"]] + ([6334] if name == "qdrant" else [])
    return [PORT]


def _url(callee: str) -> str:
    if callee == "qdrant":
        return "http://qdrant:6333"
    if callee == "postgres":
        return ""  # reached through DATABASE_URL (a Secret: it carries the password)
    return f"http://{callee}:{PORT}"


def _env(name: str) -> list[dict[str, Any]]:
    env: list[dict[str, Any]] = [
        {"name": "CONFIG_DIR", "value": "/etc/idea-validator"},
        {"name": "LOG_LEVEL", "value": "INFO"},
    ]
    for callee in sorted(edges()[name]):
        if callee == "postgres":
            continue
        if callee in (
            "redis",
            "redis-tools",
        ):  # the URL carries the password: a Secret, never a literal
            key = "REDIS_URL" if callee == "redis" else "TOOLS_REDIS_URL"
            env.append(
                {
                    "name": "REDIS_URL",
                    "valueFrom": {"secretKeyRef": {"name": "app-secrets", "key": key}},
                }
            )
            continue
        var = URL_ENV.get((name, callee), f"{callee.upper()}_URL")
        env.append({"name": var, "value": _url(callee)})
    env += [{"name": k, "value": v} for k, v in SERVICES[name].get("extra_env", {}).items()]
    if pvc := SERVICES[name].get("pvc"):
        env.append({"name": "TRACE_DIR", "value": pvc["mount"]})
    for key in ["INTERNAL_TOKEN", *SERVICES[name]["secrets"]]:
        env.append(
            {"name": key, "valueFrom": {"secretKeyRef": {"name": "app-secrets", "key": key}}}
        )
    return env


def _meta(name: str, module: str | None = None) -> dict[str, Any]:
    labels = {"app": name, "app.kubernetes.io/part-of": NAMESPACE}
    if module:
        labels["module"] = module
    return {"name": name, "namespace": NAMESPACE, "labels": labels}


def _dump(*docs: dict[str, Any]) -> str:
    return HEADER + "---\n".join(
        yaml.safe_dump(d, sort_keys=False, default_flow_style=False) for d in docs
    )


def _deployment(name: str) -> str:
    svc = SERVICES[name]
    container = {
        "name": name,
        "image": f"{NAMESPACE}/{name}:{IMAGE_TAG}",
        "ports": [{"name": "http", "containerPort": PORT}],
        "env": _env(name),
        "readinessProbe": {"httpGet": {"path": "/ready", "port": "http"}, "periodSeconds": 5},
        "livenessProbe": {
            "httpGet": {"path": "/health", "port": "http"},
            "periodSeconds": 10,
            "failureThreshold": 3,
        },
        "resources": svc.get("resources", RESOURCES),
        "securityContext": {
            "allowPrivilegeEscalation": False,
            "readOnlyRootFilesystem": True,
            "capabilities": {"drop": ["ALL"]},
        },
        "volumeMounts": [
            {"name": "tmp", "mountPath": TMP_MOUNT},
            {"name": "app-config", "mountPath": "/etc/idea-validator", "readOnly": True},
        ],
    }
    deployment = {
        "apiVersion": "apps/v1",
        "kind": "Deployment",
        "metadata": _meta(name, svc["module"]),
        "spec": {
            "replicas": svc["replicas"],
            "strategy": {
                "type": "RollingUpdate",
                "rollingUpdate": {"maxUnavailable": 0, "maxSurge": 1},
            },
            "selector": {"matchLabels": {"app": name}},
            "template": {
                "metadata": {"labels": {"app": name, "module": svc["module"]}},
                "spec": {
                    "serviceAccountName": "app",
                    "automountServiceAccountToken": False,
                    "securityContext": {
                        "runAsNonRoot": True,
                        "runAsUser": 10001,
                        "runAsGroup": 10001,
                        "fsGroup": 10001,
                        "seccompProfile": {"type": "RuntimeDefault"},
                    },
                    "containers": [container],
                    "volumes": [
                        {"name": "tmp", "emptyDir": {}},
                        {"name": "app-config", "configMap": {"name": "app-config"}},
                    ],
                },
            },
        },
    }
    service = {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": _meta(name, svc["module"]),
        "spec": {
            "selector": {"app": name},
            "ports": [{"name": "http", "port": PORT, "targetPort": "http"}],
        },
    }
    if "grace_s" in svc:
        deployment["spec"]["template"]["spec"]["terminationGracePeriodSeconds"] = svc["grace_s"]
    docs = [deployment, service]
    if pvc := svc.get("pvc"):
        pod = deployment["spec"]["template"]["spec"]
        container["volumeMounts"].append({"name": "data", "mountPath": pvc["mount"]})
        pod["volumes"].append({"name": "data", "persistentVolumeClaim": {"claimName": pvc["name"]}})
        deployment["spec"]["strategy"] = {"type": "Recreate"}
        docs.append(
            {
                "apiVersion": "v1",
                "kind": "PersistentVolumeClaim",
                "metadata": _meta(pvc["name"], svc["module"]),
                "spec": {
                    "accessModes": ["ReadWriteOnce"],
                    "resources": {"requests": {"storage": pvc["storage"]}},
                },
            }
        )
    return _dump(*docs)



def _simple() -> dict[str, str]:
    namespace = {
        "apiVersion": "v1",
        "kind": "Namespace",
        "metadata": {
            "name": NAMESPACE,
            "labels": {
                f"pod-security.kubernetes.io/{m}": "restricted"
                for m in ("enforce", "audit", "warn")
            },
        },
    }
    account = {
        "apiVersion": "v1",
        "kind": "ServiceAccount",
        "metadata": {"name": "app", "namespace": NAMESPACE},
        "automountServiceAccountToken": False,
    }
    ingress = {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "Ingress",
        "metadata": {
            "name": "idea-validator",
            "namespace": NAMESPACE,
            "annotations": {
                "nginx.ingress.kubernetes.io/use-regex": "true",
                "nginx.ingress.kubernetes.io/rewrite-target": "/$1$2",
            },
        },
        "spec": {
            "ingressClassName": "nginx",
            "rules": [
                {
                    "http": {
                        "paths": [
                            {
                                "path": "/api/(health|auth|profile|validate|discover|runs|ideas|versions|compare|history|events)(.*)",
                                "pathType": "ImplementationSpecific",
                                "backend": {
                                    "service": {"name": "gateway", "port": {"name": "http"}}
                                },
                            }
                        ]
                    }
                }
            ],
        },  # only the public API prefixes: /metrics, /ready and anything else stay cluster-internal. `/` -> ui comes with P1-T03
    }
    hpa = {
        "apiVersion": "autoscaling/v2",
        "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": "gateway", "namespace": NAMESPACE},
        "spec": {
            "scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": "gateway"},
            "minReplicas": 2,
            "maxReplicas": 5,
            "metrics": [
                {
                    "type": "Resource",
                    "resource": {
                        "name": "cpu",
                        "target": {"type": "Utilization", "averageUtilization": 70},
                    },
                }
            ],
        },
    }
    return {
        "k8s/base/namespace.yaml": _dump(namespace),
        "k8s/base/serviceaccount.yaml": _dump(account),
        "k8s/base/ingress.yaml": _dump(ingress),
        "k8s/base/ingress-ui.yaml": _dump(_ui_ingress()),
        "k8s/base/hpa.yaml": _dump(hpa),
    }


def _kustomization() -> str:
    resources = (
        ["namespace.yaml", "serviceaccount.yaml"]
        + [f"data/{n}.yaml" for n in DATA]
        + [f"services/{n}.yaml" for n in SERVICES]
        + ["services/ui.yaml"]
        + [f"jobs/{n}.yaml" for n, spec in JOBS.items() if not spec.get("manual")]
        + [f"cronjobs/{n}.yaml" for n in CRONJOBS]
        + [
            "ingress.yaml",
            "ingress-ui.yaml",
            "hpa.yaml",
            "netpol/default-deny.yaml",
            "netpol/services.yaml",
            "netpol/tools-internet.yaml",
        ]
    )
    doc = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "namespace": NAMESPACE,
        "resources": resources,
        "configMapGenerator": [
            {
                "name": "app-config",
                "files": [
                    f"../../config/{f}.yaml" for f in ("verdict", "budgets", "sources", "llm")
                ],
            }
        ],
    }
    return (
        HEADER
        + "# Build with: kubectl kustomize --load-restrictor=LoadRestrictionsNone (config/ lives outside k8s/)\n"
        + yaml.safe_dump(doc, sort_keys=False)
    )


def _overlay() -> str:
    doc = {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "resources": ["../../base"],
        "images": [
            {"name": f"{NAMESPACE}/{n}", "newName": f"localhost:5001/{n}", "newTag": "dev"}
            for n in [*SERVICES, "ui"]
        ],
        "replicas": [{"name": n, "count": 1} for n in [*SERVICES, "ui"]],
        "patches": [
            {
                "target": {"kind": "HorizontalPodAutoscaler", "name": "gateway"},
                "patch": yaml.safe_dump(
                    [{"op": "replace", "path": "/spec/minReplicas", "value": 1}]
                ),
            }
        ],
    }
    return (
        HEADER
        + "# kind overlay: one replica each, images from the local registry. deploy.sh sets the real tag.\n"
        + yaml.safe_dump(doc, sort_keys=False)
    )


def render() -> dict[str, str]:
    files = {
        "k8s/base/kustomization.yaml": _kustomization(),
        "k8s/overlays/dev/kustomization.yaml": _overlay(),
        "k8s/base/netpol/services.yaml": _netpols(),
        "k8s/base/netpol/tools-internet.yaml": _tools_internet(),
        **_simple(),
    }
    for name in SERVICES:
        files[f"k8s/base/services/{name}.yaml"] = _deployment(name)
    files["k8s/base/services/ui.yaml"] = _ui_workload()
    for name in DATA:
        files[f"k8s/base/data/{name}.yaml"] = _statefulset(name)
    for name, spec in JOBS.items():
        folder = "k8s/jobs" if spec.get("manual") else "k8s/base/jobs"
        files[f"{folder}/{name}.yaml"] = _job(name)
    for name in CRONJOBS:
        files[f"k8s/base/cronjobs/{name}.yaml"] = _cronjob(name)
    return files


def main() -> int:
    files = render()
    if "--check" in sys.argv:
        stale = [
            p for p, t in files.items() if not (ROOT / p).exists() or (ROOT / p).read_text() != t
        ]
        print("stale: " + ", ".join(stale) if stale else "k8s manifests are up to date")
        return 1 if stale else 0
    for rel, text in files.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"wrote {len(files)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

from datetime import datetime
from typing import Any, Protocol

from ..models.traces import IndexRow, RunSummary


class TraceIndex(Protocol):
    async def insert_new(self, rows: list[IndexRow]) -> set[str]:
        """Insert rows; return the record ids that were new (conflicts are skipped)."""
        ...

    async def delete(self, run_id: str, record_ids: set[str]) -> None: ...

    async def list_runs(
        self, limit: int, after: tuple[datetime, str] | None
    ) -> list[RunSummary]: ...

    async def ping(self) -> bool: ...


class TraceFiles(Protocol):
    def prepare(self) -> None: ...
    def writable(self) -> bool: ...
    def append(self, run_id: str, items: list[tuple[str, dict[str, Any]]]) -> None: ...
    def exists(self, run_id: str) -> bool: ...
    def read(self, run_id: str, limit: int) -> tuple[list[tuple[str, dict[str, Any]]], bool]: ...

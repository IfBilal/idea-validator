import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { RouterProvider, createMemoryHistory } from "@tanstack/react-router";
import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { http, HttpResponse } from "msw";
import { setupServer } from "msw/node";
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it } from "vitest";
import { clearSession, resetAuthForTests, setSession } from "@/lib/auth";
import { makeRouter } from "@/router";
import fixtures from "./fixtures/gateway_ideas.json";

// Fixtures were generated by instantiating the gateway pydantic models (services/gateway models/ideas.py).
const API = "http://gw.test";
const A = "11111111-1111-4111-8111-111111111111";
const B = "22222222-2222-4222-8222-222222222222";
const server = setupServer();
beforeAll(() => server.listen({ onUnhandledFrame: "error" }));
afterAll(() => server.close());
beforeEach(() => {
  window.__APP_CONFIG__ = { API_BASE_URL: API };
  window.sessionStorage.clear();
  resetAuthForTests();
  setSession("tok", 3600);
});
afterEach(() => {
  server.resetHandlers();
  clearSession();
});

function renderAt(path: string) {
  const router = makeRouter(createMemoryHistory({ initialEntries: [path] }));
  render(
    <QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}>
      <RouterProvider router={router} />
    </QueryClientProvider>,
  );
  return router;
}

const json = (body: unknown, status = 200) => HttpResponse.json(body as object, { status });
const cardOf = (id: string) => (id === A ? fixtures.card_a : fixtures.card_b);

describe("History", () => {
  it("lists ideas with latest verdict, score and date, exactly as returned", async () => {
    server.use(http.get(`${API}/ideas`, () => json(fixtures.page)));
    renderAt("/history");
    const list = await screen.findByRole("list", { name: /your ideas/i });
    const first = within(list).getAllByRole("listitem")[0]!;
    expect(within(first).getByText("Notion exporter")).toBeInTheDocument();
    expect(within(first).getByText("GO")).toBeInTheDocument();
    expect(within(first).getByText("70.5")).toBeInTheDocument();
    expect(within(first).getByText(/2026-11-01/)).toBeInTheDocument();
    expect(within(first).getByRole("link", { name: /versions of notion exporter/i })).toHaveAttribute("href", `/ideas/${A}`);
    const second = within(list).getAllByRole("listitem")[1]!;
    expect(within(second).getByText(/no verdict yet/i)).toBeInTheDocument();
  });

  it("pages with the cursor from the server", async () => {
    const seen: (string | null)[] = [];
    server.use(
      http.get(`${API}/ideas`, ({ request }) => {
        const cursor = new URL(request.url).searchParams.get("cursor");
        seen.push(cursor);
        return json(cursor ? { items: [{ ...fixtures.page.items[0], idea_id: B, title: "Second page idea" }], next_cursor: null } : fixtures.page);
      }),
    );
    renderAt("/history");
    await userEvent.click(await screen.findByRole("button", { name: /load more/i }));
    expect(await screen.findByText("Second page idea")).toBeInTheDocument();
    expect(seen).toEqual([null, "cur2"]);
    expect(screen.queryByRole("button", { name: /load more/i })).not.toBeInTheDocument();
  });

  it("shows an empty state", async () => {
    server.use(http.get(`${API}/ideas`, () => json({ items: [], next_cursor: null })));
    renderAt("/history");
    expect(await screen.findByText(/no ideas yet/i)).toBeInTheDocument();
  });

  it("shows an error when the call fails", async () => {
    server.use(http.get(`${API}/ideas`, () => json({ error: { code: "INTERNAL", message: "boom", request_id: "r9" } }, 500)));
    renderAt("/history");
    expect(await screen.findByRole("alert")).toHaveTextContent(/r9/);
  });

  it("fails closed on a malformed page (unknown verdict label)", async () => {
    const bad = { ...fixtures.page, items: [{ ...fixtures.page.items[0], latest_verdict: "MAYBE" }] };
    server.use(http.get(`${API}/ideas`, () => json(bad)));
    renderAt("/history");
    expect(await screen.findByRole("alert")).toHaveTextContent(/something went wrong|does not understand|try again/i);
    expect(screen.queryByText("Notion exporter")).not.toBeInTheDocument();
  });
});

describe("Versions", () => {
  it("lists versions with a link to each stored card", async () => {
    server.use(http.get(`${API}/ideas/${A}/versions`, () => json(fixtures.versions)));
    renderAt(`/ideas/${A}`);
    const list = await screen.findByRole("list", { name: /versions/i });
    const items = within(list).getAllByRole("listitem");
    expect(items).toHaveLength(2);
    expect(within(items[0]!).getByText("narrowed scope")).toBeInTheDocument();
    expect(within(items[0]!).getByText("70.5")).toBeInTheDocument();
    expect(within(items[0]!).getByRole("link", { name: /open card for version 2/i })).toHaveAttribute("href", `/ideas/${A}?v=2`);
    expect(within(items[1]!).getByText(/no verdict yet/i)).toBeInTheDocument();
  });

  it("still opens the verdict card when a version is chosen", async () => {
    server.use(http.get(`${API}/ideas/${A}/versions/2`, () => json(fixtures.card_a)));
    renderAt(`/ideas/${A}?v=2`);
    expect(await screen.findByText(/idea card/i)).toBeInTheDocument();
    expect(await screen.findByText("GO")).toBeInTheDocument();
  });

  it("shows error and fails closed on malformed data", async () => {
    server.use(http.get(`${API}/ideas/${A}/versions`, () => json([{ ...fixtures.versions[0], version: "two" }])));
    renderAt(`/ideas/${A}`);
    expect(await screen.findByRole("alert")).toBeInTheDocument();
  });

  it("shows an empty state", async () => {
    server.use(http.get(`${API}/ideas/${A}/versions`, () => json([])));
    renderAt(`/ideas/${A}`);
    expect(await screen.findByText(/no versions/i)).toBeInTheDocument();
  });
});

describe("Compare", () => {
  const cards = () =>
    http.get(`${API}/ideas/:id/versions/:v`, ({ params }) => json(cardOf(String(params.id))));

  it("compares two ideas side by side and marks the differences", async () => {
    let ids = "";
    server.use(
      http.get(`${API}/compare`, ({ request }) => {
        ids = new URL(request.url).searchParams.get("ids") ?? "";
        return json(fixtures.compare);
      }),
      cards(),
    );
    renderAt(`/compare?a=${A}&b=${B}`);
    const table = await screen.findByRole("table", { name: /comparison/i });
    expect(ids).toBe(`${A},${B}`);
    const row = (name: RegExp) => within(table).getByRole("row", { name });
    // competition 2 vs 4: differs; feasibility 4 vs 4: same
    expect(row(/competition/i)).toHaveTextContent(/2/);
    expect(row(/competition/i)).toHaveTextContent(/differs/i);
    expect(row(/^feasibility \d/i)).not.toHaveTextContent(/differs/i);
    expect(row(/verdict/i)).toHaveTextContent("GO");
    expect(row(/verdict/i)).toHaveTextContent("NO-GO");
    expect(row(/verdict/i)).toHaveTextContent(/differs/i);
    expect(row(/overall score/i)).toHaveTextContent("70.5");
    expect(row(/overall score/i)).toHaveTextContent(/no score/i);
    expect(row(/confidence/i)).toHaveTextContent("0.825");
    expect(row(/risk gate/i)).toHaveTextContent(/pass/i);
    expect(row(/risk gate/i)).toHaveTextContent(/fail/i);
    expect(row(/duplicate gate/i)).toHaveTextContent(/not evaluated/i);
  });

  it("compares two versions from their stored cards without calling /compare", async () => {
    let compareCalls = 0;
    server.use(
      http.get(`${API}/compare`, () => {
        compareCalls++;
        return json(fixtures.compare);
      }),
      cards(),
    );
    renderAt(`/compare?a=${A}:2&b=${B}:1`);
    const table = await screen.findByRole("table", { name: /comparison/i });
    expect(within(table).getByRole("row", { name: /overall score/i })).toHaveTextContent("70.5");
    expect(within(table).getByRole("row", { name: /confidence/i })).toHaveTextContent("0.825");
    expect(compareCalls).toBe(0);
  });

  it("fails closed when the comparison is malformed", async () => {
    server.use(http.get(`${API}/compare`, () => json({ ...fixtures.compare, verdicts: { [A]: "MAYBE" } })), cards());
    renderAt(`/compare?a=${A}&b=${B}`);
    expect(await screen.findByRole("alert")).toBeInTheDocument();
    expect(screen.queryByRole("table")).not.toBeInTheDocument();
  });

  it("shows an error from the gateway", async () => {
    server.use(http.get(`${API}/compare`, () => json({ error: { code: "NOT_FOUND", message: "no", request_id: "r1" } }, 404)));
    renderAt(`/compare?a=${A}&b=${B}`);
    expect(await screen.findByRole("alert")).toBeInTheDocument();
  });

  it("says when the gates are unavailable instead of guessing", async () => {
    server.use(
      http.get(`${API}/compare`, () => json(fixtures.compare)),
      http.get(`${API}/ideas/:id/versions/:v`, () => json({ ...fixtures.card_a, card: null, verdict: null, score: null, stability: null })),
    );
    renderAt(`/compare?a=${A}&b=${B}`);
    const table = await screen.findByRole("table", { name: /comparison/i });
    await waitFor(() => expect(within(table).getByRole("row", { name: /risk gate/i })).toHaveTextContent(/unavailable/i));
  });

  it("lets the user pick two ideas and versions, then compares", async () => {
    server.use(
      http.get(`${API}/ideas`, () => json({ items: fixtures.page.items, next_cursor: null })),
      http.get(`${API}/ideas/:id/versions`, () => json(fixtures.versions)),
      http.get(`${API}/compare`, () => json(fixtures.compare)),
      cards(),
    );
    const router = renderAt("/compare");
    await screen.findAllByRole("option", { name: "Notion exporter" });
    await userEvent.selectOptions(screen.getByLabelText(/first idea/i), A);
    await userEvent.selectOptions(screen.getByLabelText(/second idea/i), B);
    await userEvent.click(screen.getByRole("button", { name: /compare/i }));
    await screen.findByRole("table", { name: /comparison/i });
    expect(router.state.location.search).toMatchObject({ a: A, b: B });
  });

  it("refuses to compare an idea with itself", async () => {
    server.use(
      http.get(`${API}/ideas`, () => json({ items: fixtures.page.items, next_cursor: null })),
      http.get(`${API}/ideas/:id/versions`, () => json(fixtures.versions)),
    );
    renderAt("/compare");
    await screen.findAllByRole("option", { name: "Notion exporter" });
    await userEvent.selectOptions(screen.getByLabelText(/first idea/i), A);
    await userEvent.selectOptions(screen.getByLabelText(/second idea/i), A);
    await userEvent.click(screen.getByRole("button", { name: /compare/i }));
    expect(await screen.findByRole("alert")).toHaveTextContent(/two different/i);
  });
});

describe("Navigation", () => {
  it("has History and Compare entries", async () => {
    server.use(http.get(`${API}/ideas`, () => json(fixtures.page)));
    renderAt("/history");
    const nav = await screen.findByRole("navigation", { name: /main/i });
    expect(within(nav).getByRole("link", { name: "History" })).toHaveAttribute("href", "/history");
    expect(within(nav).getByRole("link", { name: "Compare" })).toHaveAttribute("href", "/compare");
  });
});

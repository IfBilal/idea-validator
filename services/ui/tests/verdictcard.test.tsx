import { readFileSync } from "node:fs";
import { join } from "node:path";
import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import { VerdictCard } from "@/components/VerdictCard";
import { parseCard, safeHref } from "@/lib/verdict";
import go from "./fixtures/m11_go.json";
import goStable from "./fixtures/m11_go_stable_what_if.json";
import insufficientLowConfidence from "./fixtures/m11_insufficient_low_confidence.json";
import insufficientAbstained from "./fixtures/m11_insufficient_risk_abstained.json";
import insufficientTwoSources from "./fixtures/m11_insufficient_two_sources.json";
import nogoLowScore from "./fixtures/m11_nogo_low_score_no_failed_gate.json";
import nogoFeasibility from "./fixtures/m11_nogo_gate_feasibility.json";
import nogoRisk from "./fixtures/m11_nogo_gate_risk.json";
import pivot from "./fixtures/m11_pivot_with_what_if.json";
import pivotFloor from "./fixtures/m11_pivot_floor_breach.json";

type Card = Record<string, unknown>;
const card = (base: unknown, over: Card = {}): Card => ({ ...(base as Card), ...over });
const verdictWords = /^(GO|PIVOT|NO-GO)$/;

describe("real M11 cards (generated by services/verdict, see eval/verdict/make_ui_fixtures.py)", () => {
  it("GO: badge, stability, score, confidence, six dimensions with their weights, versions", () => {
    render(<VerdictCard raw={go} />);
    const region = screen.getByRole("region", { name: "Verdict" });
    expect(within(region).getByText("GO")).toBeInTheDocument();
    expect(within(region).getByText("BORDERLINE")).toBeInTheDocument();
    expect(within(region).getByText("70.5")).toBeInTheDocument();
    expect(within(region).getByText("0.825")).toBeInTheDocument();
    expect(within(region).getByText(/decision support, not a prediction of success/i)).toBeInTheDocument();
    expect(within(region).getByText(/engine m11@v1/i)).toBeInTheDocument();
    const comp = screen.getByRole("listitem", { name: "Competition" });
    expect(within(comp).getByText("2 / 5")).toBeInTheDocument();
    expect(within(comp).getByText("weight 15")).toBeInTheDocument();
    expect(within(comp).getByText(/confidence/)).toBeInTheDocument();
    expect(screen.getByText("4 of 14 checks change the verdict.")).toBeInTheDocument();
    expect(screen.queryByText(/what would make this go/i)).not.toBeInTheDocument();
    expect(screen.getByText(/GO at 70, NO-GO below 50, minimum dimension score 1.5/)).toBeInTheDocument();
  });

  it("GO (stable): shows STABLE", () => {
    render(<VerdictCard raw={goStable} />);
    expect(screen.getByText("STABLE")).toBeInTheDocument();
    expect(screen.getByText("73.5")).toBeInTheDocument();
  });

  it("PIVOT: shows what would make it GO, with the engine's numbers and nullable fields", () => {
    render(<VerdictCard raw={pivot} />);
    expect(screen.getByText("PIVOT")).toBeInTheDocument();
    expect(screen.getByText(/what would make this go/i)).toBeInTheDocument();
    const list = screen.getByText(/what would make this go/i).parentElement as HTMLElement;
    expect(list.textContent).toMatch(/\(GO/);
  });

  it("PIVOT from a floor breach names the weakest dimension from the engine", () => {
    render(<VerdictCard raw={pivotFloor} />);
    expect(screen.getByText(/Weakest dimension: Competition/)).toBeInTheDocument();
  });

  it("NO-GO by a failed gate: gates verbatim in three states, reasons from M11, no UI-made sentence", () => {
    render(<VerdictCard raw={nogoFeasibility} />);
    expect(screen.getByText("NO-GO")).toBeInTheDocument();
    const gates = screen.getByRole("list", { name: "Gates" });
    expect(within(gates).getByRole("listitem", { name: "Feasibility: fail" })).toBeInTheDocument();
    expect(within(gates).getByRole("listitem", { name: "Evidence: pass" })).toBeInTheDocument();
    expect(within(gates).getByRole("listitem", { name: "Risk: not evaluated" })).toBeInTheDocument();
    expect(within(gates).getByRole("listitem", { name: "Duplicate: not evaluated" })).toBeInTheDocument();
    expect(screen.queryByText(/blocked by/i)).not.toBeInTheDocument();
    const why = screen.getByRole("list", { name: "Why" });
    expect(within(why).getAllByRole("listitem").length).toBeGreaterThan(0);
    expect(screen.queryByText(/\/ 100/)).not.toBeInTheDocument(); // the engine gave no score
  });

  it("NO-GO by a failed risk gate", () => {
    render(<VerdictCard raw={nogoRisk} />);
    expect(screen.getByRole("listitem", { name: "Risk: fail" })).toBeInTheDocument();
  });

  it("NO-GO by a low score with no failed gate is valid and shows its score", () => {
    render(<VerdictCard raw={nogoLowScore} />);
    expect(screen.getByText("NO-GO")).toBeInTheDocument();
    expect(screen.getByText("49")).toBeInTheDocument();
    expect(screen.queryByRole("alert")).not.toBeInTheDocument();
  });

  it("INSUFFICIENT_EVIDENCE from a failed evidence gate: only missing, reasons, gates, confidence", () => {
    render(<VerdictCard raw={insufficientTwoSources} />);
    expect(screen.getByText("NOT ENOUGH EVIDENCE")).toBeInTheDocument();
    expect(screen.getByText("1 more independent source(s)")).toBeInTheDocument();
    expect(screen.getByRole("listitem", { name: "Evidence: fail" })).toBeInTheDocument();
    expect(screen.queryByText(verdictWords)).not.toBeInTheDocument();
  });

  it("INSUFFICIENT_EVIDENCE that carries extra engine fields hides scores, sensitivity and what-would-make-GO", () => {
    // this real card has score 80 (the engine computed one) but confidence 0.39: it must not be shown
    expect((insufficientLowConfidence as Card).score).toBe(80);
    render(<VerdictCard raw={insufficientLowConfidence} />);
    expect(screen.getByText("0.39")).toBeInTheDocument();
    expect(screen.queryByText("80")).not.toBeInTheDocument();
    expect(screen.queryByText(/\/ 100/)).not.toBeInTheDocument();
    expect(screen.queryByText("Six dimensions")).not.toBeInTheDocument();
    expect(screen.queryByText("Stability")).not.toBeInTheDocument();
    expect(screen.queryByText(/what would make this go/i)).not.toBeInTheDocument();
    expect(screen.queryByText(/weight /)).not.toBeInTheDocument();
    expect(screen.getByText("stronger evidence for demand_pain")).toBeInTheDocument();
  });

  it("INSUFFICIENT_EVIDENCE because a scorer abstained", () => {
    render(<VerdictCard raw={insufficientAbstained} />);
    expect(screen.getByText("evidence for risk")).toBeInTheDocument();
    expect(screen.queryByText(/\/ 100/)).not.toBeInTheDocument();
  });
});

describe("the card as stored by M3", () => {
  it("accepts the explicit nulls M3 adds when it re-serialises the verdict (features, fallback, ...)", () => {
    const padded = card(go, {
      scores: ((go as Card).scores as Card[]).map((s) => ({ ...s, features: null, fallback: null, adjusted_by_challenge: null })),
      missing: null,
      reasons: null,
    });
    expect(parseCard(padded).kind).toBe("settled");
    render(<VerdictCard raw={padded} />);
    expect(screen.getByText("70.5")).toBeInTheDocument();
  });
});

describe("numbers are shown exactly as received", () => {
  it("69.96 is not rounded up to 70 and the verdict is still PIVOT", () => {
    render(<VerdictCard raw={card(pivot, { score: 69.96 })} />);
    expect(screen.getByText("69.96")).toBeInTheDocument();
    expect(screen.queryByText("70")).not.toBeInTheDocument();
  });

  it("confidence 0.495 stays 0.495 (an INSUFFICIENT card below 0.5 must not read 0.50)", () => {
    render(<VerdictCard raw={card(insufficientLowConfidence, { confidence: 0.495 })} />);
    expect(screen.getByText("0.495")).toBeInTheDocument();
  });

  it("69.9667 keeps its four decimals", () => {
    render(<VerdictCard raw={card(pivot, { score: 69.9667 })} />);
    expect(screen.getByText("69.9667")).toBeInTheDocument();
  });
});

describe("fail closed on contradictory or malformed cards", () => {
  const contradictions: [string, unknown][] = [
    ["GO together with partial: true", card(go, { partial: true })],
    ["a score but no verdict", { verdict: null, partial: true, score: 80, needs_input: [] }],
    ["a verdict field missing entirely", { score: 80, confidence: 0.8 }],
    ["verdict null without partial", { verdict: null, needs_input: [] }],
    ["NO-GO with neither a failed gate nor a score", card(nogoFeasibility, { gates: { evidence: "pass", feasibility: "pass", risk: "pass", duplicate: "pass" } })],
    ["GO without a stability", card(go, { stability: null })],
    ["PIVOT without a score", card(pivot, { score: null })],
    ["GO with a failed gate", card(go, { gates: { evidence: "pass", feasibility: "fail", risk: "pass", duplicate: "pass" } })],
    ["an unknown verdict label", card(go, { verdict: "MAYBE" })],
    ["a gate state the schema does not know", card(go, { gates: { evidence: "pass", feasibility: "ok", risk: "pass", duplicate: "pass" } })],
    ["null", null],
    ["a string", "GO"],
    ["an array", []],
  ];
  it.each(contradictions)("%s -> error alert, no verdict", (_name, raw) => {
    render(<VerdictCard raw={raw} />);
    expect(screen.getByRole("alert")).toHaveTextContent(/could not be displayed/i);
    expect(screen.queryByText(verdictWords)).not.toBeInTheDocument();
    expect(screen.queryByText(/\/ 100/)).not.toBeInTheDocument();
  });
});


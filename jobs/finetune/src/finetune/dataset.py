"""Build ``train.jsonl``, ``val.jsonl``, ``test.jsonl`` and the data README (P8-T04).

* every example is schema-validated first (a bad row fails the build);
* the TEST set is exactly the hand-checked examples (by idea); no idea is ever in two parts;
* the grouped split and the overlap assertion against the labelled verdict set run on every build;
* the count of hand-checked examples is reported, never adjusted: too few fails the build.
"""

import argparse
import json
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from .schema import validate_example
from .split import assert_no_overlap, grouped_split
from .strat import stratification_report

SEED = 42
MIN_CHECKED = 60


class DatasetError(ValueError):
    """The dataset cannot be built honestly."""


def _flat(ex: Mapping[str, Any]) -> dict[str, Any]:
    meta = ex["meta"]
    return {
        "idea_id": meta["idea_id"],
        "idea_text": meta.get("idea_text"),
        "dimension": meta["dimension"],
        "level": meta["level"],
        "row": ex,
    }


def _write(path: Path, parts: Sequence[Mapping[str, Any]]) -> None:
    with open(path, "w", encoding="utf-8") as handle:
        for item in parts:
            handle.write(json.dumps(item["row"], ensure_ascii=False) + "\n")


def build_dataset(
    examples: Sequence[Mapping[str, Any]],
    *,
    labelled: Sequence[Mapping[str, Any]],
    out_dir: Path,
    seed: int = SEED,
    min_checked: int = MIN_CHECKED,
    allow_no_test: bool = False,
) -> dict[str, Any]:
    for ex in examples:
        v = validate_example(dict(ex))
        if v.meta.synthetic:
            raise DatasetError("synthetic example in the real dataset")
    flat = [_flat(ex) for ex in examples]
    checked = [r for r in flat if r["row"]["meta"]["hand_checked"]]
    if len(checked) < min_checked:
        raise DatasetError(
            f"only {len(checked)} hand-checked examples, need {min_checked}: "
            "a human must review more (finetune.review); this count is never adjusted"
        )
    assert_no_overlap(flat, labelled)
    test_ideas = {r["idea_id"] for r in checked}
    parts = grouped_split(flat, test_ideas=test_ideas, val_fraction=0.1, seed=seed)
    test_rows = [r for r in flat if r["idea_id"] in test_ideas and r["row"]["meta"]["hand_checked"]]
    if not test_rows and not allow_no_test:
        raise DatasetError("no hand-checked test examples")
    out_dir.mkdir(parents=True, exist_ok=True)
    _write(out_dir / "train.jsonl", parts["train"])
    _write(out_dir / "val.jsonl", parts["val"])
    if test_rows:
        _write(out_dir / "test.jsonl", test_rows)
    stats: dict[str, Any] = {
        "seed": seed,
        "status": "ok" if test_rows else "draft-only: no hand-checked test set yet",
        "counts": {"train": len(parts["train"]), "val": len(parts["val"]), "test": len(test_rows)},
        "ideas": {
            "train": len({r["idea_id"] for r in parts["train"]}),
            "val": len({r["idea_id"] for r in parts["val"]}),
            "test": len(test_ideas),
        },
        "overlap_with_labelled": "none (asserted)",
        "stratification": {
            "train": stratification_report(parts["train"]),
            "val": stratification_report(parts["val"]),
            "test": stratification_report(test_rows),
        },
    }
    (out_dir / "stats.json").write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    (out_dir / "README.md").write_text(render_readme(stats), encoding="utf-8")
    return stats


def render_readme(stats: Mapping[str, Any]) -> str:
    lines = [
        "# Fine-tuning dataset (generated by `python -m finetune.dataset`; do not edit by hand)",
        "",
        f"split: grouped by idea, seed: {stats['seed']}, status: {stats['status']}",
        "",
        "## Provenance",
        "- Ideas: product cards, gap-derived and paraphrased user-style ideas from the project KB "
        "(never Reddit text, never the labelled verdict set).",
        "- Evidence: top-k retrieval with the same code as production.",
        "- Draft labels: a hosted model (`draft_model` in each example's `meta`), temperature 0.",
        "- The test set is the human-reviewed examples only (`hand_checked: true`, with",
        "  `checked_by`, `checked_at`, `original_label`, `final_label`).",
        "  Train and validation are unreviewed drafts.",
        "",
        "## Counts",
        f"examples: {stats['counts']}",
        f"ideas: {stats['ideas']}",
        f"overlap with eval/labelled: {stats['overlap_with_labelled']}",
        "",
        "## Examples per dimension x level (train)",
        "",
        "| dimension | " + " | ".join(f"L{lv}" for lv in range(6)) + " |",
        "|---|" + "---|" * 6,
    ]
    strat = stats["stratification"]["train"]
    for dim, row in strat["counts"].items():
        lines.append(f"| {dim} | " + " | ".join(str(row[str(lv)]) for lv in range(6)) + " |")
    lines += [
        "",
        f"cells below {strat['min_cell']} examples: {strat['under_filled'] or 'none'}",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> None:
    from .prompting import repo_root

    p = argparse.ArgumentParser(prog="finetune.dataset")
    p.add_argument("--drafts", default="jobs/finetune/data/drafts.jsonl")
    p.add_argument("--reviews-dir", default="jobs/finetune/data/reviews")
    p.add_argument("--out", default="jobs/finetune/data")
    p.add_argument("--min-checked", type=int, default=MIN_CHECKED)
    a = p.parse_args(argv)
    from .review import load_reviews, merge_reviews

    root = repo_root()
    drafts = [
        json.loads(x) for x in Path(a.drafts).read_text(encoding="utf-8").splitlines() if x.strip()
    ]
    reviews = load_reviews(Path(a.reviews_dir)) if Path(a.reviews_dir).exists() else []
    merged, conflicts = merge_reviews(drafts, reviews)
    if conflicts:
        print(f"{len(conflicts)} reviewer disagreements left unchecked: {conflicts[:5]} ...")
    labelled: list[dict[str, Any]] = []
    for name in ("labelled_set.jsonl", "candidates.jsonl"):
        path = root / "eval" / "labelled" / name
        if path.exists():
            labelled += [
                json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()
            ]
    if not labelled:
        raise DatasetError("eval/labelled has no items: refusing to claim zero overlap")
    stats = build_dataset(merged, labelled=labelled, out_dir=Path(a.out), min_checked=a.min_checked)
    print(json.dumps(stats["counts"]), stats["status"])


if __name__ == "__main__":
    main()
